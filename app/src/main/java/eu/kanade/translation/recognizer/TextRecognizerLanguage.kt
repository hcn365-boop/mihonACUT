    fun toTranslatorLanguage(): TextTranslatorLanguage =
        TextTranslatorLanguage.entries.firstOrNull {
            it.name.equals(name, ignoreCase = true) || it.code.equals(code, ignoreCase = true)
        } ?: TextTranslatorLanguage.ENGLISH

    companion object {
        fun fromPref(pref: Preference<String>): TextRecognizerLanguage {
            val name = pref.get()
            val lang = entries.firstOrNull { it.name.equals(name, true) }
            if (lang == null) {
                pref.set(CHINESE.name)
                return CHINESE
            }
            return lang
        }
    }
